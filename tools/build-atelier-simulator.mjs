import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const postcss = createRequire(join(ROOT, '../Q-Atelier/package.json'))('postcss');
const normalized = text => text.replaceAll('\r\n', '\n');

export function composeSimulator({ template, components, foundation, palette, recipe, fontResources }) {
  if (template.split('{{QD_SIMULATOR_CSS}}').length !== 2) throw new Error('One simulator CSS slot required');
  const autoLight = postcss.atRule({ name: 'media', params: 'screen and (prefers-color-scheme: light)' });
  postcss.parse(palette).walkRules(rule => {
    if (rule.selector === "html:root[data-theme='light']") autoLight.append(rule.clone({ selector: "html:root:not([data-theme='dark'])" }));
  });
  if (!autoLight.nodes?.length) throw new Error('Canonical light palette missing');
  const css = [fontResources, components, foundation, palette, autoLight.toString(), recipe].join('\n');
  const ast = postcss.parse(css), definitions = new Set(), required = new Set();
  ast.walkDecls(decl => {
    if (decl.prop.startsWith('--')) definitions.add(decl.prop);
    for (const match of decl.value.matchAll(/var\(\s*(--[\w-]+)\s*\)/g)) required.add(match[1]);
  });
  const missing = [...required].filter(name => !definitions.has(name));
  if (missing.length) throw new Error(`Unbound standalone CSS variables: ${missing.join(', ')}`);
  return normalized(template.replace('{{QD_SIMULATOR_CSS}}', css));
}

export function buildAtelierSimulator(root = ROOT, { check = false } = {}) {
  const read = file => readFileSync(join(root, file), 'utf8');
  const html = composeSimulator({
    template: read('patterns/foundation/atelier-simulator.html'),
    recipe: read('patterns/foundation/atelier-simulator.css'),
    components: read('patterns/components.css'), foundation: read('patterns/foundation.css'),
    palette: read('dist/q-design.palette.atelier.css'),
    // Font-face metadata is generated by the existing licensed font resource pipeline.
    // It contains binary-resource URLs and ranges, not screen-specific typography.
    fontResources: read('../Q-Atelier/app/fonts.css'),
  });
  const output = join(root, 'dist/q-design.simulator.atelier.html');
  if (check) {
    if (!existsSync(output) || normalized(readFileSync(output, 'utf8')) !== html) throw new Error('Standalone simulator output stale');
  } else writeFileSync(output, html);
  return output;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is supported');
  console.log(`Simulator ${process.argv.includes('--check') ? 'checked' : 'built'}: ${buildAtelierSimulator(ROOT, { check: process.argv.includes('--check') })}`);
}
