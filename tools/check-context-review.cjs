    await page.locator('#note').fill('저장 중 추가로 작성한 메모');
    await page.waitForFunction(() => document.getElementById('save-feedback').textContent.includes('추가 변경'));
    assert.equal(await page.locator('#save').isEnabled(), true);
    passed('저장 도중 추가 입력의 미저장 상태 유지');
    await page.locator('#save').click(); await row('002').click();
    assert.equal(await selectedTitle(), '위험관리 계획서'); await page.waitForTimeout(750);
