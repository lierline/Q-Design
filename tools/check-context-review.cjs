    passed('문서별 미저장 메모와 체크 상태 유지');
    await page.locator('#complete').click();
    assert.match(await page.locator('#save-error').textContent(), /확인 항목/);
    assert.equal(await page.locator('#checklist input').nth(1).evaluate(el => el === document.activeElement), true);
    passed('검토 완료 조건과 오류 초점');
    await page.locator('#list-scroll').evaluate(el => { el.scrollTop = 250; });
    const listTop = await page.locator('#list-scroll').evaluate(el => el.scrollTop);
    await page.locator('#detail-scroll').evaluate(el => { el.scrollTop = 120; });
    const detailTop = await page.locator('#detail-scroll').evaluate(el => el.scrollTop);
    await page.locator('#focus-view').click(); await waitMotion();
    assert.equal(await page.locator('#list-pane').isVisible(), false);
    await page.locator('#back').click(); await waitMotion();
    assert.equal(await page.locator('#list-scroll').evaluate(el => el.scrollTop), listTop);
    assert.equal(await page.locator('#detail-scroll').evaluate(el => el.scrollTop), detailTop);
    passed('집중 보기 후 목록과 상세 읽기 위치 복원');
    await page.locator('#settings summary').click(); await page.locator('#fail-save').check(); await page.locator('#settings summary').click();
    await page.locator('#save').click();
    await page.waitForFunction(() => document.getElementById('save-error').textContent.includes('저장하지 못했습니다'));
    assert.match(await page.locator('#note').inputValue(), /사용 조건/);
    await page.locator('#save').click();
    await page.waitForFunction(() => document.getElementById('save-feedback').textContent.includes('저장했습니다'));
    passed('저장 실패, 초안 보존, 재시도');
