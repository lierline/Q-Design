    await page.locator('#back').click(); await waitMotion();
    assert.equal(await page.locator('#search').inputValue(), '위험');
    assert.equal(await page.locator('#status-filter').inputValue(), 'review');
    assert.equal(await page.locator('#sort').inputValue(), 'name');
    assert.equal(await row('002').evaluate(el => el === document.activeElement), true);
    await page.goBack(); await waitMotion(); assert.equal(await selectedTitle(), '위험관리 계획서');
