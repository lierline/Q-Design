import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readRuntimeValues, resolveAtelierMedia } from './atelier-runtime-values.mjs';
import { readOutputValues, resolveAtelierOutputCss } from './atelier-output-values.mjs';
import { validateTypographyLinks } from './typography-links-core.mjs';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const postcss = require('postcss');
export const PRODUCTS = ['atelier', 'maison', 'carnet'];
const normalized = value => value.replaceAll('\r\n', '\n');
export function offlineRevision(html) {
  const digest = createHash('sha256').update(normalized(html)).digest('hex').slice(0, 16);
  return `// Generated from the standalone offline HTML. Import from the service worker.\nself.QD_OFFLINE_CACHE = 'q-offline-${digest}';\n`;
}

export function composeFoundation(shared, recipe, product, links = '') {
  if (!PRODUCTS.includes(product)) throw new Error(`Unknown foundation product ${product}`);
  for (const [label, css] of [['shared', shared], [product, recipe], ['typography-links', links]]) {
    const ast = postcss.parse(css, { from: `foundation/${label}.css` });
    ast.walkAtRules('import', () => { throw new Error(`${label}: imports belong in the product entrypoint`); });
    ast.walkDecls(decl => {
      if (decl.prop.startsWith('--qd-') && !decl.value.trim()) throw new Error(`${label}: empty token ${decl.prop}`);
    });
  }
  // Product selectors follow defaults so scoped variants remain intentional.
  const output = `/* Generated by build-foundation.mjs. Edit patterns/foundation.css or patterns/foundation/${product}.css. */\n${normalized(shared).trimEnd()}\n\n${normalized(recipe).trimEnd()}\n`;
  return links ? `${output.trimEnd()}\n\n${normalized(links).trimEnd()}\n` : output;
}

export function validateSharedAliases(shared, componentCss) {
  const definitions = new Map();
  postcss.parse(componentCss + '\n' + shared).walkDecls(decl => {
    if (decl.prop.startsWith('--qd-')) definitions.set(decl.prop, decl.value);
  });
  const graph = new Map();
  postcss.parse(shared).walkDecls(decl => {
    if (!decl.prop.startsWith('--qd-')) return;
    const refs = [...decl.value.matchAll(/var\(\s*(--qd-[\w-]+)\s*([,)])/g)];
    for (const [, name, end] of refs) if (end === ')' && !definitions.has(name)) throw new Error(`Undefined foundation token ${name} in ${decl.prop}`);
    graph.set(decl.prop, refs.map(match => match[1]));
  });
  function visit(name, path = []) {
    if (path.includes(name)) throw new Error(`Foundation token cycle: ${[...path, name].join(' -> ')}`);
    for (const next of graph.get(name) ?? []) visit(next, [...path, name]);
  }
  for (const name of graph.keys()) visit(name);
}

export function buildFoundation(root = ROOT, { check = false, only = PRODUCTS } = {}) {
  const shared = readFileSync(join(root, 'patterns/foundation.css'), 'utf8');
  const links = readFileSync(join(root, 'patterns/typography-links.css'), 'utf8');
  validateTypographyLinks(shared, links, postcss);
  validateSharedAliases(shared, readFileSync(join(root, 'patterns/components.css'), 'utf8'));
  for (const product of only) {
    let recipe = readFileSync(join(root, `patterns/foundation/${product}.css`), 'utf8');
    if (product === 'atelier' && /qd-bp\(/.test(recipe)) recipe = resolveAtelierMedia(recipe, readRuntimeValues(root));
    if (product === 'atelier' && /qd-output\(/.test(recipe)) recipe = resolveAtelierOutputCss(recipe, readOutputValues(root));
    for (const suffix of ['values', 'core-values']) {
      const valuesPath = join(root, `patterns/foundation/${product}-${suffix}.css`);
      if (existsSync(valuesPath)) recipe += '\n' + readFileSync(valuesPath, 'utf8');
    }
    const output = composeFoundation(shared, recipe, product, links);
    const path = join(root, `dist/q-design.foundation.${product}.css`);
    if (check) {
      if (!existsSync(path) || normalized(readFileSync(path, 'utf8')) !== output) throw new Error(`Foundation output stale: ${product}`);
    } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, output); }
  }
  if (only.includes('atelier')) {
    const templatePath=join(root,'patterns/foundation/atelier-offline.html');
    if (existsSync(templatePath)) {
      const template=readFileSync(templatePath,'utf8');
      const css=[readFileSync(join(root,'patterns/components.css'),'utf8'),shared,readFileSync(join(root,'dist/q-design.palette.atelier.css'),'utf8'),readFileSync(join(root,'patterns/foundation/offline.css'),'utf8')].join('\n');
      postcss.parse(css);
      const html=normalized(template.replace('{{QD_OFFLINE_CSS}}',css));
      const path=join(root,'dist/q-design.offline.atelier.html');
      if(check){if(!existsSync(path)||normalized(readFileSync(path,'utf8'))!==html)throw new Error('Offline output stale');}
      else writeFileSync(path,html);
      const revision=offlineRevision(html), revisionPath=join(root,'dist/q-design.offline-revision.atelier.js');
      if(check){if(!existsSync(revisionPath)||normalized(readFileSync(revisionPath,'utf8'))!==revision)throw new Error('Offline revision stale');}
      else writeFileSync(revisionPath,revision);
    }
  }
  return only;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check' && !arg.startsWith('--only='))) throw new Error('Use --check and optional --only=atelier,maison,carnet');
  const only = args.find(arg => arg.startsWith('--only='))?.slice(7).split(',') ?? PRODUCTS;
  console.log(`Foundation ${args.includes('--check') ? 'checked' : 'built'}: ${buildFoundation(ROOT, { check: args.includes('--check'), only }).join(', ')}`);
}
