import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { buildPalettes, readInputs } from './build-palette.mjs';
const ROOT=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const postcss=require('postcss');

// Resolve through the same validated shared override pipeline as the web UI.
// Email clients need concrete inline values, so CSS custom properties cannot be sent.
export function resolveEmailPalette(inputs, mappings) {
  const css=postcss.parse(buildPalettes(...inputs).atelier);
  const selectors=inputs[1].products.atelier.selectors;
  const themes={dark:{},light:{}};
  css.walkRules(rule=>{
    const theme=Object.keys(selectors).find(key=>selectors[key]===rule.selector);
    if(theme)rule.walkDecls(decl=>{themes[theme][decl.prop]=decl.value;});
  });
  return Object.fromEntries(Object.entries(mappings).map(([name,spec])=>{
    if(!/^[a-zA-Z][a-zA-Z0-9]*$/.test(name)||Object.keys(spec).some(key=>!['theme','token'].includes(key)))throw new Error(`Invalid email mapping: ${name}`);
    const value=themes[spec.theme]?.[spec.token];
    if(!/^#[\da-f]{6}$/i.test(value??''))throw new Error(`Email mapping ${name} requires a resolved six-digit color: ${spec.theme}.${spec.token}`);
    return [name,value];
  }));
}
export function buildEmailPalette(root=ROOT,{check=false}={}) {
  const mappings=JSON.parse(readFileSync(join(root,'patterns/foundation/maison-email-palette.json'),'utf8'));
  const palette=resolveEmailPalette(readInputs(root),mappings);
  const output='/* Generated by tools/build-maison-email.mjs. Edit central palette mappings and overrides. */\nexport const EMAIL_PALETTE = '+JSON.stringify(palette,null,2)+' as const;\n';
  const path=join(root,'dist/q-design.email-palette.maison.ts');
  if(check){if(!existsSync(path)||readFileSync(path,'utf8').replaceAll('\r\n','\n')!==output)throw new Error('Maison email palette is stale.');}
  else writeFileSync(path,output);
  return palette;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  if(process.argv.slice(2).some(arg=>arg!=='--check'))throw new Error('Use optional --check.');
  buildEmailPalette(ROOT,{check:process.argv.includes('--check')});
  console.log('Maison email palette '+(process.argv.includes('--check')?'checked':'built'));
}
