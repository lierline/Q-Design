// Native wrappers use the same offline layout, text rules and product palettes.
// Only source assets are synchronized. Existing signed APKs are immutable.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import {resolveHtmlMetrics} from './build-atelier-html.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const postcss=createRequire(path.resolve(ROOT,'../Q-Works/package.json'))('postcss');
export const NATIVE_OFFLINE=[
  {key:'Q-Atelier',product:'atelier',name:'Q-Atelier',scheme:'qatelier-app',targets:['Q-Atelier-App/app/src/main/assets/offline.html','Q-Atelier-iOS/QAtelier/Resources/offline.html']},
  {key:'Q-Works',product:'maison',name:'Q-Maison',scheme:'maison-app',targets:['Q-Maison-App/app/src/main/assets/offline.html']},
  {key:'Q-Forge',product:'carnet',name:'Q-Carnet',scheme:'carnet-app',targets:['Q-Carnet-App/app/src/main/assets/offline.html']},
];
const norm=value=>value.replaceAll('\r\n','\n');
export function nativeTypographyXml(root){
 const foundation=fs.readFileSync(path.join(root,'patterns/foundation.css'),'utf8'),components=fs.readFileSync(path.join(root,'patterns/components.css'),'utf8');
 const metrics=resolveHtmlMetrics(components,foundation),values={};
 postcss.parse(foundation).walkRules(rule=>{if(rule.selector===':root'&&rule.parent.type==='root')rule.walkDecls(decl=>{values[decl.prop]=decl.value;});});
 const px=value=>{if(!/^\d+(?:\.\d+)?px$/.test(value))throw Error('Native dimension must resolve to positive px: '+value);return Number.parseFloat(value);};
 return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by Q-Design/tools/build-native-offline.mjs. Sizes use sp for Android font scaling. -->\n<resources>\n    <dimen name="qd_native_hint_size">${px(metrics.controlSize)}sp</dimen>\n    <dimen name="qd_native_wordmark_size">${px(values['--qd-native-wordmark-size'])}sp</dimen>\n    <dimen name="qd_native_text_inset">${px(values['--qd-native-text-inset'])}dp</dimen>\n</resources>\n`;
}
export function nativeTypographySwift(root){
 const xml=nativeTypographyXml(root),dimension=name=>{
  const match=xml.match(new RegExp(`<dimen name="${name}">(\\d+(?:\\.\\d+)?)(?:sp|dp)</dimen>`));
  if(!match)throw Error('Missing native dimension: '+name);return match[1];
 };
 return `// Generated by Q-Design/tools/build-native-offline.mjs.\nimport CoreGraphics\n\nenum QDesignTypography {\n    static let hintPointSize: CGFloat = ${dimension('qd_native_hint_size')}\n    static let wordmarkPointSize: CGFloat = ${dimension('qd_native_wordmark_size')}\n    static let textInset: CGFloat = ${dimension('qd_native_text_inset')}\n}\n`;
}
export function nativeOfflineHtml(root,config){
 const css=['patterns/components.css','patterns/foundation.css',`dist/q-design.palette.${config.product}.css`,'patterns/foundation/offline.css'].map(file=>fs.readFileSync(path.join(root,file),'utf8')).join('\n');
 if(/<\/style/i.test(css))throw Error('Unsafe embedded stylesheet');
 const template=fs.readFileSync(path.join(root,'patterns/foundation/native-offline.html'),'utf8');
 return '<!-- Generated by Q-Design/tools/build-native-offline.mjs. Edit the canonical offline template, layout and product palette. -->\n'+norm(template).replace('{{PRODUCT_NAME}}',config.name).replace('{{RETRY_SCHEME}}',config.scheme).replace('{{STYLES}}',norm(css));
}
export function buildNativeOffline(root=ROOT,{check=false,write=false,only=null}={}){
 const selected=NATIVE_OFFLINE.filter(config=>!only||only.has(config.key)),results=[];
 for(const config of selected){
  const html=nativeOfflineHtml(root,config),dist=path.join(root,`dist/q-design.native-offline.${config.product}.html`);
  if(check){if(!fs.existsSync(dist)||norm(fs.readFileSync(dist,'utf8'))!==html)throw Error('Stale native offline output: '+config.product);}
  else fs.writeFileSync(dist,html);
  for(const target of config.targets){
   const full=path.resolve(root,'..',target);
   if(!fs.existsSync(full))throw Error('Missing native wrapper source: '+target);
   if(write)fs.writeFileSync(full,html);
   if((check||write)&&norm(fs.readFileSync(full,'utf8'))!==html)throw Error('Stale native wrapper asset: '+target);
   results.push({product:config.product,target,synchronized:check||write});
  }
  const wrapper=config.targets.find(target=>target.includes('/app/src/main/assets/')).split('/app/')[0];
  const xml=nativeTypographyXml(root),xmlDist=path.join(root,`dist/q-design.native-typography.${config.product}.xml`),xmlTarget=wrapper+'/app/src/main/res/values/q_design_typography.xml',xmlFull=path.resolve(root,'..',xmlTarget);
  if(check){if(!fs.existsSync(xmlDist)||norm(fs.readFileSync(xmlDist,'utf8'))!==xml)throw Error('Stale native typography output: '+config.product);}
  else fs.writeFileSync(xmlDist,xml);
  if(write)fs.writeFileSync(xmlFull,xml);
  if((check||write)&&(!fs.existsSync(xmlFull)||norm(fs.readFileSync(xmlFull,'utf8'))!==xml))throw Error('Stale native typography resource: '+xmlTarget);
  results.push({product:config.product,target:xmlTarget,synchronized:check||write});
  if(config.product==='atelier'){
   const swift=nativeTypographySwift(root),swiftDist=path.join(root,'dist/q-design.native-typography.atelier.swift'),swiftTarget='Q-Atelier-iOS/QAtelier/Sources/QDesignTypography.swift',swiftFull=path.resolve(root,'..',swiftTarget);
   if(check){if(!fs.existsSync(swiftDist)||norm(fs.readFileSync(swiftDist,'utf8'))!==swift)throw Error('Stale iOS typography output');}
   else fs.writeFileSync(swiftDist,swift);
   if(write)fs.writeFileSync(swiftFull,swift);
   if((check||write)&&(!fs.existsSync(swiftFull)||norm(fs.readFileSync(swiftFull,'utf8'))!==swift))throw Error('Stale iOS typography source');
   results.push({product:config.product,target:swiftTarget,synchronized:check||write});
  }
 }
 return results;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href){
 const args=process.argv.slice(2);if(args.some(arg=>!['--check','--write'].includes(arg)&&!arg.startsWith('--only=')))throw Error('Use --check, --write and optional --only.');
 if(args.includes('--check')&&args.includes('--write'))throw Error('Check and write are exclusive.');
 const onlyArg=args.find(arg=>arg.startsWith('--only=')),only=onlyArg?new Set(onlyArg.slice(7).split(',')):null;
 console.log(JSON.stringify(buildNativeOffline(ROOT,{check:args.includes('--check'),write:args.includes('--write'),only}),null,2));
}
