import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(resolve(root, 'patterns/icons.json'), 'utf8'));
const check = process.argv.includes('--check');
const outputs = new Map();
const ids = new Set();
const icons = catalog.icons.map(icon => {
  if (!/^[a-z][a-z-]*$/.test(icon.id) || ids.has(icon.id)) throw new Error(`Invalid or duplicate icon: ${icon.id}`);
  ids.add(icon.id);
  const svg = readFileSync(resolve(root, `vendor/phosphor/regular/${icon.source}.svg`), 'utf8');
  if (!svg.includes('viewBox="0 0 256 256"') || /<(script|foreignObject|image|use|style)\b|\bon\w+\s*=|\bhref\s*=|<!DOCTYPE|<!ENTITY/i.test(svg)) {
    throw new Error(`Unexpected SVG content: ${icon.source}`);
  }
  outputs.set(`dist/icons/${icon.id}.svg`, svg);
  return { ...icon, file: `icons/${icon.id}.svg`, sha256: createHash('sha256').update(svg).digest('hex') };
});
const css = `/* Generated by tools/build-icons.mjs. Phosphor Icons, MIT. License: icons/LICENSE. */
.qd-icon {
  display: inline-block;
  width: var(--qd-icon-size, 20px);
  height: var(--qd-icon-size, 20px);
  flex: 0 0 auto;
  vertical-align: -0.18em;
  color: inherit;
  background-color: currentColor;
  -webkit-mask: var(--qd-icon-image) center / contain no-repeat;
  mask: var(--qd-icon-image) center / contain no-repeat;
}
.qd-icon--sm { --qd-icon-size: 16px; }
.qd-icon--lg { --qd-icon-size: 24px; }
.qd-icon-label { display: inline-flex; align-items: center; gap: 8px; }
@media (forced-colors: active) { .qd-icon { forced-color-adjust: none; } }
` + icons.map(i => `.qd-icon[data-icon="${i.id}"] { --qd-icon-image: url("./${i.file}"); }`).join('\n') + '\n';
outputs.set('dist/q-design.icons.css', css);
outputs.set('dist/q-design.icons.json', JSON.stringify({ ...catalog, icons }, null, 2) + '\n');
outputs.set('dist/icons/LICENSE', readFileSync(resolve(root, 'vendor/phosphor/LICENSE'), 'utf8'));
for (const [file, content] of outputs) {
  const path = resolve(root, file);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) throw new Error(`Out of date: ${file}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
console.log(`${check ? 'Verified' : 'Built'} ${icons.length} icons at ${catalog.commit.slice(0, 12)}; local assets only.`);
