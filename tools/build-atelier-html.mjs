import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveEmailPalette } from './build-maison-email.mjs';
import { readInputs } from './build-palette.mjs';
import { createRequire } from 'node:module';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const postcss = createRequire(import.meta.url)('postcss');

export function resolveHtmlMetrics(componentCss, foundationCss) {
  const values = {};
  for (const source of [foundationCss, componentCss]) postcss.parse(source).walkRules(rule => {
    if (rule.selector === ':root' && rule.parent.type === 'root') rule.walkDecls(d => { values[d.prop] = d.value; });
  });
  const resolveValue = (value, depth = 0) => {
    if (depth > 12) throw new Error('Cyclic HTML metric');
    return value.replace(/var\((--[\w-]+)(?:,\s*([^()]+))?\)/g, (_, key, fallback) => {
      if (!values[key] && !fallback) throw new Error(`Unresolved HTML metric ${key}`);
      return resolveValue(values[key] ?? fallback, depth + 1);
    });
  };
  const names = { radius: '--qd-radius', controlHeight: '--qd-control-height', controlSize: '--qd-control-size', bodySize: '--qd-body-size', captionSize: '--qd-caption-size', titleSize: '--qd-title-size', sectionSize: '--qd-section-size', overlayTitleSize: '--qd-overlay-title-size', fontUI: '--qd-font-family-ui', fontMono: '--qd-font-family-mono', fontBrand: '--qd-font-family-brand' };
  return Object.fromEntries(Object.entries(names).map(([name, token]) => {
    if (!values[token]) throw new Error(`Missing HTML metric ${token}`);
    const value = resolveValue(values[token]);
    if (/[<>]|var\(/.test(value)) throw new Error(`Invalid HTML metric ${token}`);
    return [name, value];
  }));
}

export function resolveHtmlPalette(inputs, mappings) {
  const shared = {}, concrete = {};
  for (const [name, spec] of Object.entries(mappings)) {
    if ('value' in spec) {
      if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(name) || !/^#[\da-f]{6}$/i.test(spec.value) || !spec.reason || Object.keys(spec).some(k => !['value', 'reason'].includes(k))) throw new Error(`Invalid concrete HTML palette entry: ${name}`);
      concrete[name] = spec.value;
    } else shared[name] = spec;
  }
  return { ...resolveEmailPalette(inputs, shared), ...concrete };
}

export function buildHtmlPalette(root = ROOT, { check = false } = {}) {
  const mappings = JSON.parse(readFileSync(join(root, 'patterns/foundation/atelier-html-palette.json'), 'utf8'));
  const palette = resolveHtmlPalette(readInputs(root), mappings);
  const metrics = resolveHtmlMetrics(readFileSync(join(root, 'patterns/components.css'), 'utf8'), readFileSync(join(root, 'patterns/foundation.css'), 'utf8'));
  const output = '/* Generated by tools/build-atelier-html.mjs. Edit Q-Design palette mappings/overrides and shared component/foundation rules. */\nexport const HTML_PALETTE = ' + JSON.stringify(palette, null, 2) + ' as const;\nexport const HTML_METRICS = ' + JSON.stringify(metrics, null, 2) + ' as const;\n';
  const file = join(root, 'dist/q-design.html-palette.atelier.ts');
  if (check) { if (!existsSync(file) || readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Atelier HTML palette is stale.'); }
  else writeFileSync(file, output);
  return palette;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Use optional --check.');
  buildHtmlPalette(ROOT, { check: process.argv.includes('--check') });
  console.log('Atelier HTML palette ' + (process.argv.includes('--check') ? 'checked' : 'built'));
}
